def get_uvicorn_pid() -> int:
    """Finds the PID of running uvicorn process."""
    try:
        res = subprocess.run(
            ["ps", "aux"], capture_output=True, text=True, check=True
        )
        for line in res.stdout.splitlines():
            if "uvicorn" in line and "app.main:app" in line and "grep" not in line:
                parts = line.split()
                return int(parts[1])
    except Exception:
        pass
    return 0


def sample_process_metrics(pid: int) -> Tuple[float, float]:
    """Samples CPU% and RAM RSS (MB) of target PID using ps."""
    if pid <= 0:
        return 0.0, 0.0
    try:
        res = subprocess.run(
            ["ps", "-o", "%cpu,rss", "-p", str(pid)],
            capture_output=True,
            text=True,
            check=True,
        )
        lines = res.stdout.strip().splitlines()
        if len(lines) > 1:
            parts = lines[1].split()
            cpu_pct = float(parts[0])
            rss_mb = float(parts[1]) / 1024.0
            return cpu_pct, rss_mb
    except Exception:
        pass
    return 0.0, 0.0


def get_postgres_connection_count() -> int:
    """Queries total active connection count from PostgreSQL pg_stat_activity."""
    try:
        from dotenv import load_dotenv
        import os
        import psycopg2

        load_dotenv()
        db_url = os.getenv("DATABASE_URL", "")
        if not db_url or "postgresql" not in db_url:
            return 0
        if db_url.startswith("postgresql+psycopg2://"):
            db_url = db_url.replace("postgresql+psycopg2://", "postgresql://")

        conn = psycopg2.connect(db_url, connect_timeout=5)
        cur = conn.cursor()
        cur.execute("SELECT count(*) FROM pg_stat_activity;")
        cnt = cur.fetchone()[0]
        cur.close()
        conn.close()
        return cnt
    except Exception:
        return -1


async def send_single_request(
    client: httpx.AsyncClient, question: str, req_idx: int
) -> Dict[str, Any]:
    """Sends a single POST /api/chat request and records detailed latency and status."""
    payload = {"team_name": TEAM_NAME, "question": question}
    t_start = time.perf_counter()

    result = {
        "req_idx": req_idx,
        "question": question,
        "status_code": 0,
        "latency_seconds": 0.0,
        "success": False,
        "is_timeout": False,
        "error": None,
        "answer_len": 0,
    }

    try:
        response = await client.post(CHAT_ENDPOINT, json=payload)
        t_duration = time.perf_counter() - t_start
        result["latency_seconds"] = round(t_duration, 4)
        result["status_code"] = response.status_code

        if response.status_code == 200:
            data = response.json()
            answer = data.get("answer", "")
            result["answer_len"] = len(answer)
            if answer and len(answer.strip()) > 0:
                result["success"] = True
            else:
                result["error"] = "Empty answer in 200 OK response"
        else:
            result["error"] = f"HTTP {response.status_code}: {response.text[:200]}"

    except httpx.TimeoutException as exc:
        t_duration = time.perf_counter() - t_start
        result["latency_seconds"] = round(t_duration, 4)
        result["is_timeout"] = True
        result["error"] = f"TimeoutException after {t_duration:.2f}s: {exc}"
    except Exception as exc:
        t_duration = time.perf_counter() - t_start
        result["latency_seconds"] = round(t_duration, 4)
        result["error"] = f"Exception: {exc}"

    return result


async def run_benchmark_level(
    concurrency: int, uvicorn_pid: int
) -> Dict[str, Any]:
    """Runs a single concurrency benchmark level (sending $concurrency requests simultaneously)."""
    print("\n" + "=" * 90)
    print(f" 🧪 RUNNING BENCHMARK LEVEL: CONCURRENCY = {concurrency}")
    print("=" * 90)

    questions = QUESTIONS_POOL[:concurrency]
    print(f"Prepared {len(questions)} distinct questions for concurrency={concurrency}.")

    pg_conns_before = get_postgres_connection_count()
    print(f"PostgreSQL Active Connections Before Batch: {pg_conns_before}")

    # Set generous timeout (90s) to allow capturing high-concurrency queued requests
    timeout = httpx.Timeout(90.0, connect=30.0)
    limits = httpx.Limits(max_keepalive_connections=concurrency, max_connections=concurrency + 10)

    # Monitor metrics during execution
    cpu_samples = []
    ram_samples = []
    stop_sampling = False

    async def sampler():
        while not stop_sampling:
            cpu, rss = sample_process_metrics(uvicorn_pid)
            if cpu > 0 or rss > 0:
                cpu_samples.append(cpu)
                ram_samples.append(rss)
            await asyncio.sleep(0.5)

    sampler_task = asyncio.create_task(sampler())

    t_wall_start = time.perf_counter()

    async with httpx.AsyncClient(timeout=timeout, limits=limits) as client:
        tasks = [
            send_single_request(client, q, idx + 1)
            for idx, q in enumerate(questions)
        ]
        results = await asyncio.gather(*tasks, return_exceptions=False)

    t_wall_duration = time.perf_counter() - t_wall_start
    stop_sampling = True
    await sampler_task

    pg_conns_after = get_postgres_connection_count()

    # Process metrics
    latencies = [r["latency_seconds"] for r in results]
    successes = [r for r in results if r["success"]]
    failures = [r for r in results if not r["success"]]
    timeouts = [r for r in results if r["is_timeout"]]

    # Percentiles
    sorted_lat = sorted(latencies)
    num_reqs = len(sorted_lat)

    def calc_percentile(p: float) -> float:
        if not sorted_lat:
            return 0.0
        idx = int(p * num_reqs)
        idx = min(idx, num_reqs - 1)
        return round(sorted_lat[idx], 3)

    min_lat = round(min(sorted_lat), 3) if sorted_lat else 0.0
    avg_lat = round(sum(sorted_lat) / len(sorted_lat), 3) if sorted_lat else 0.0
    p50_lat = calc_percentile(0.50)
    p95_lat = calc_percentile(0.95)
    p99_lat = calc_percentile(0.99)
    max_lat = round(max(sorted_lat), 3) if sorted_lat else 0.0
    throughput = round(len(successes) / t_wall_duration, 3) if t_wall_duration > 0 else 0.0

    avg_cpu = round(sum(cpu_samples) / len(cpu_samples), 1) if cpu_samples else 0.0
    max_cpu = round(max(cpu_samples), 1) if cpu_samples else 0.0
    avg_ram = round(sum(ram_samples) / len(ram_samples), 1) if ram_samples else 0.0
    max_ram = round(max(ram_samples), 1) if ram_samples else 0.0

    status_codes: Dict[str, int] = {}
    for r in results:
        code_str = str(r["status_code"]) if r["status_code"] > 0 else ("TIMEOUT" if r["is_timeout"] else "ERROR")
        status_codes[code_str] = status_codes.get(code_str, 0) + 1

    summary = {
        "concurrency": concurrency,
        "total_requests": len(results),
        "successful_requests": len(successes),
        "failed_requests": len(failures),
        "timeout_count": len(timeouts),
        "wall_clock_duration_seconds": round(t_wall_duration, 3),
        "throughput_req_per_sec": throughput,
        "latency": {
            "min_seconds": min_lat,
            "avg_seconds": avg_lat,
            "p50_seconds": p50_lat,
            "p95_seconds": p95_lat,
            "p99_seconds": p99_lat,
            "max_seconds": max_lat,
        },
        "status_code_distribution": status_codes,
        "resources": {
            "uvicorn_pid": uvicorn_pid,
            "avg_cpu_pct": avg_cpu,
            "max_cpu_pct": max_cpu,
            "avg_ram_mb": avg_ram,
            "max_ram_mb": max_ram,
            "postgres_conns_before": pg_conns_before,
            "postgres_conns_after": pg_conns_after,
        },
        "requests": results,
    }

    print(f"  Total Requests:       {len(results)}")
    print(f"  Successes:            {len(successes)}")
    print(f"  Failures:             {len(failures)}")
    print(f"  Timeouts:             {len(timeouts)}")
    print(f"  Wall-Clock Duration:  {t_wall_duration:.3f}s")
    print(f"  Throughput:           {throughput:.3f} req/s")
    print(f"  Latencies (s):        Min={min_lat}s | Avg={avg_lat}s | P50={p50_lat}s | P95={p95_lat}s | P99={p99_lat}s | Max={max_lat}s")
    print(f"  Uvicorn CPU%:         Avg={avg_cpu}% | Max={max_cpu}%")
    print(f"  Uvicorn RAM (MB):     Avg={avg_ram} MB | Max={max_ram} MB")
    print(f"  PostgreSQL Conns:     Before={pg_conns_before} | After={pg_conns_after}")
    print(f"  Status Codes:         {status_codes}")

    return summary


async def main():
    print("\n" + "=" * 90)
    print(" 🚀 TECHONOMY READ-ONLY CONCURRENCY BASELINE BENCHMARK")
    print(f" Target Endpoint: {CHAT_ENDPOINT}")
    print(f" Team Name: {TEAM_NAME}")
    print("=" * 90)

    uvicorn_pid = get_uvicorn_pid()
    print(f"Identified Uvicorn Process PID: {uvicorn_pid}")
    if uvicorn_pid <= 0:
        print("⚠️ Warning: Uvicorn PID not found via ps. Resource monitoring may be limited.")

    # 1. Ensure Team Exists
    async with httpx.AsyncClient(timeout=10.0) as init_client:
        try:
            team_res = await init_client.post(
                f"{BASE_URL}/api/teams/join",
                json={"team_name": TEAM_NAME, "member_names": ["BenchmarkUser"]},
            )
            print(f"Registered/Verified benchmark team '{TEAM_NAME}' (HTTP {team_res.status_code}).")
        except Exception as e:
            print(f"⚠️ Could not verify team '{TEAM_NAME}': {e}")

    levels = [1, 5, 10, 25, 50]
    all_summaries = []

    for lvl in levels:
        summary = await run_benchmark_level(lvl, uvicorn_pid)
        all_summaries.append(summary)
        # Wait 3 seconds between benchmark levels for server stabilization
        await asyncio.sleep(3.0)

    # Save Results
    results_dir = PROJECT_ROOT / "scripts" / "results"
    results_dir.mkdir(parents=True, exist_ok=True)

    timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
    raw_json_file = results_dir / f"concurrency_benchmark_{timestamp_str}.json"
    summary_md_file = results_dir / f"concurrency_summary_{timestamp_str}.md"

    # Export Raw JSON
    with open(raw_json_file, "w", encoding="utf-8") as f:
        json.dump(
            {
                "timestamp": datetime.now().isoformat(),
                "endpoint": CHAT_ENDPOINT,
                "team_name": TEAM_NAME,
                "benchmarks": all_summaries,
            },
            f,
            indent=2,
        )
    print(f"\nSaved raw JSON benchmark data to:\n  {raw_json_file}")

    # Build Markdown Summary Table
    md_content = []
    md_content.append(f"# Techonomy Read-Only Concurrency Baseline Test Summary")
    md_content.append(f"**Date/Time**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    md_content.append(f"**Endpoint**: `{CHAT_ENDPOINT}`")
    md_content.append(f"**Target Team**: `{TEAM_NAME}`")
    md_content.append(f"**Uvicorn Process PID**: `{uvicorn_pid}`\n")
    md_content.append("## Concurrency Benchmark Results Table\n")
    md_content.append("| Concurrency | Success | Failures | Timeouts | P50 (s) | P95 (s) | P99 (s) | Max (s) | Throughput (req/s) | Avg CPU (%) | Max RAM (MB) |")
    md_content.append("| ----------: | ------: | -------: | -------: | ------: | ------: | ------: | ------: | ----------------: | ----------: | -----------: |")

    for s in all_summaries:
        c = s["concurrency"]
        succ = s["successful_requests"]
        fail = s["failed_requests"]
        tout = s["timeout_count"]
        p50 = s["latency"]["p50_seconds"]
        p95 = s["latency"]["p95_seconds"]
        p99 = s["latency"]["p99_seconds"]
        max_l = s["latency"]["max_seconds"]
        tp = s["throughput_req_per_sec"]
        cpu = s["resources"]["avg_cpu_pct"]
        ram = s["resources"]["max_ram_mb"]
        md_content.append(f"| {c} | {succ} | {fail} | {tout} | {p50:.3f} | {p95:.3f} | {p99:.3f} | {max_l:.3f} | {tp:.3f} | {cpu}% | {ram} MB |")

    md_content.append("\n## Per-Level Detailed Breakdown\n")

    for s in all_summaries:
        md_content.append(f"### Concurrency Level: {s['concurrency']}")
        md_content.append(f"- **Total Requests**: {s['total_requests']}")
        md_content.append(f"- **Wall-Clock Time**: {s['wall_clock_duration_seconds']}s")
        md_content.append(f"- **Status Codes**: {s['status_code_distribution']}")
        md_content.append(f"- **PostgreSQL Connections**: Before={s['resources']['postgres_conns_before']} | After={s['resources']['postgres_conns_after']}")
        md_content.append(f"- **Uvicorn CPU**: Avg={s['resources']['avg_cpu_pct']}% | Max={s['resources']['max_cpu_pct']}%")
        md_content.append(f"- **Uvicorn RAM**: Avg={s['resources']['avg_ram_mb']} MB | Max={s['resources']['max_ram_mb']} MB\n")

    with open(summary_md_file, "w", encoding="utf-8") as f:
        f.write("\n".join(md_content))

    print(f"Saved summary report to:\n  {summary_md_file}\n")
    print("=" * 90)
    print(" ✅ CONCURRENCY BASELINE BENCHMARK COMPLETE")
    print("=" * 90 + "\n")


if __name__ == "__main__":
    asyncio.run(main())
